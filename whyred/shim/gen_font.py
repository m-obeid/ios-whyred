#!/usr/bin/env python3
"""Generate font.h (ASCII 0x20-0x7e, 8x16) from a PSF1 or PSF2 console font."""
import gzip
import struct
import sys

src = sys.argv[1]
d = gzip.open(src).read() if src.endswith('.gz') else open(src, 'rb').read()
if d[:2] == b'\x36\x04':
    off, h, w = 4, d[3], 8
elif d[:4] == b'\x72\xb5\x4a\x86':
    off = struct.unpack_from('<I', d, 8)[0]
    h, w = struct.unpack_from('<2I', d, 24)
else:
    sys.exit('not a PSF font')
if (w, h) != (8, 16):
    sys.exit(f'need an 8x16 font, got {w}x{h}')
out = [f'/* generated by gen_font.py from {src.split("/")[-1]} */',
       'static const unsigned char font8x16[95][16] = {']
for c in range(0x20, 0x7f):
    g = d[off + c * h: off + c * h + h]
    out.append('\t{' + ','.join(f'0x{b:02x}' for b in g) + '},')
out.append('};')
open('font.h', 'w').write('\n'.join(out) + '\n')
